begin;
create extension if not exists pgtap with schema extensions;
select plan(12);
select has_table('public','study_session_attendance','attendance table exists');
select has_table('public','study_session_followup','follow-up table exists');
select has_pk('public','study_session_attendance','attendance has composite primary key');
select has_pk('public','study_session_followup','follow-up has primary key');
select col_is_pk('public','study_session_attendance',array['session_id','user_id'],'attendance unique per participant and meeting');
select col_is_pk('public','study_session_followup','session_id','one follow-up record per meeting');
select col_not_null('public','study_session_attendance','recorded_by','attendance requires recorder');
select col_not_null('public','study_session_attendance','status','attendance requires status');
select col_has_default('public','study_session_attendance','recorded_at','attendance records timestamp');
select col_has_default('public','study_session_followup','updated_at','follow-up records timestamp');
select ok((select relrowsecurity from pg_class where oid='public.study_session_attendance'::regclass),'attendance RLS enabled');
select ok((select relrowsecurity from pg_class where oid='public.study_session_followup'::regclass),'follow-up RLS enabled');
select * from finish();
rollback;
